"""tools_gen_race_trace.py: write race_trace.inc.c, the one-off instrumentation that finds
the Race Editor's random-race generator (run in WSL, then install_race_trace.sh).

It wraps every function that advances rand()'s state (0x47C390), every function that uses the
Race Editor object ([0x4D32FC]), and the random-race menu's methods: each wrapper counts its
calls (and the order in which they were first called) and runs the generated body. The page
calls web_race_trace(0) to clear and start counting, presses "Create Race", then
web_race_trace(1) to print "[RTRACE] ..." lines. Functions recomp_manual.c already overrides
are left alone.
"""
import bisect, glob, os, re

HOME = os.path.expanduser('~/mc3-web')
asm = HOME + '/work-dub/analysis/disasm/asm/text.asm'
lab_rx = re.compile(r'^sub_([0-9A-F]{8}):')
starts = []
for l in open(asm, errors='replace'):
    m = lab_rx.match(l)
    if m: starts.append(int(m.group(1), 16))
starts.sort()
def fn_of(a):
    k = bisect.bisect_right(starts, a) - 1
    return starts[k] if k >= 0 else None

cands = {}
# 1. rand()'s state is stored to
fn_rx = re.compile(r'^void sub_([0-9A-F]{8})(_gen)?\(void\)')
for path in glob.glob(HOME + '/work-dub/gen/recomp_*.c'):
    fn = None
    for line in open(path, errors='replace'):
        m = fn_rx.match(line)
        if m: fn = int(m.group(1), 16); continue
        if fn is not None and 'MEM32(0x47C390) =' in line: cands[fn] = 'rand'
# 2. the Race Editor object [0x4D32FC] is used
for l in open(asm, errors='replace'):
    if l.startswith('  0x') and '0x4d32fc' in l:
        f = fn_of(int(l[4:12], 16))
        if f is not None: cands.setdefault(f, 'editor')
# 3. the random-race menu (mcMenuGenRandom) and the handlers it calls
for f in starts:
    if 0x16F0F0 <= f <= 0x16F7D0: cands.setdefault(f, 'menu')
for f in (0x11EBF0, 0x11CF90, 0x11B710, 0x113F00, 0x1145E0):
    cands.setdefault(f, 'handler')

ov = set()
for l in open(HOME + '/work-dub/gen/.manual_overrides', errors='replace'):
    m = re.search(r'sub_([0-9A-Fa-f]{8})', l)
    if m: ov.add(int(m.group(1), 16))
manual = open(HOME + '/src/games/dub/recomp_manual.c', errors='replace').read()
# (our own earlier install is stripped by the installer; anything else defined there is skipped)
manual = re.sub(r'/\* >>> mc3-web-port: race trace.*?/\* <<< mc3-web-port: race trace \*/', '', manual, flags=re.S)
for m in re.finditer(r'^void sub_([0-9A-Fa-f]{8})\(void\)', manual, re.M): ov.add(int(m.group(1), 16))
ours = sorted(f for f in cands if f not in ov)
skipped = sorted(f for f in cands if f in ov)

out = ['/* >>> mc3-web-port: race trace (installed by install_race_trace.sh; generated by',
       ' * tools_gen_race_trace.py -- regenerate, do not edit this copy) */',
       '/* One-off instrumentation to find the Race Editor\'s random-race generator: each wrapper',
       ' * counts its calls while tracing is on and runs the generated body. web_race_trace(0)',
       ' * clears and starts, (1) prints "[RTRACE] sub_X calls N first #K kind" and stops, (2) stops. */',
       '#include <stdio.h>', '#include <stdint.h>',
       '#ifdef __EMSCRIPTEN__', '#include <emscripten.h>', '#else', '#ifndef EMSCRIPTEN_KEEPALIVE',
       '#define EMSCRIPTEN_KEEPALIVE', '#endif', '#endif',
       '#define RT_N %d' % len(ours),
       'static const uint32_t rt_addr[RT_N] = {' + ','.join('0x%08X' % f for f in ours) + '};',
       'static const char rt_kind[RT_N] = {' + ','.join("'%s'" % cands[f][0] for f in ours) + '};',
       'static volatile int rt_on; static uint32_t rt_calls[RT_N], rt_first[RT_N], rt_seq;',
       'static void rt_hit(int i) { if (!rt_on) return; if (!rt_calls[i]++) rt_first[i] = ++rt_seq; }',
       'EMSCRIPTEN_KEEPALIVE void web_race_trace(int cmd)',
       '{',
       '    int i;',
       '    if (cmd == 0) { for (i = 0; i < RT_N; i++) { rt_calls[i] = 0; rt_first[i] = 0; } rt_seq = 0; rt_on = 1; return; }',
       '    rt_on = 0;',
       '    if (cmd != 1) return;',
       '    for (i = 0; i < RT_N; i++) if (rt_calls[i])',
       '        printf("[RTRACE] sub_%08X calls %u first #%u %c\\n", (unsigned)rt_addr[i], (unsigned)rt_calls[i], (unsigned)rt_first[i], rt_kind[i]);',
       '    printf("[RTRACE] end (%d functions watched)\\n", RT_N);',
       '}']
for i, f in enumerate(ours):
    out.append('extern void sub_%08X_gen(void);' % f)
    out.append('void sub_%08X(void) { rt_hit(%d); sub_%08X_gen(); }' % (f, i, f))
out.append('/* <<< mc3-web-port: race trace */')
open('/mnt/c/Games/mc3-web-port/race_trace.inc.c', 'w').write('\n'.join(out) + '\n')
print('wrapped', len(ours), '(rand %d, editor %d, menu %d, handler %d); already overridden, skipped: %s' % (
    sum(cands[f] == 'rand' for f in ours), sum(cands[f] == 'editor' for f in ours),
    sum(cands[f] == 'menu' for f in ours), sum(cands[f] == 'handler' for f in ours),
    ' '.join('sub_%08X' % f for f in skipped) or 'none'))
